test('HTTP 数据、备份、模型降级、静态资源和来源限制', async t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'human-dispatch-test-'));
  core.configureDataDirectory(directory);
  const storage = require('../storage.cjs').createStorageController({ initialDirectory: directory, configPath: path.join(directory, 'location.txt') });
  const server = createServer({ storage }); await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(async () => { await new Promise(resolve => server.close(resolve)); fs.rmSync(directory, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const get = async route => (await fetch(base + route)).json();
  const send = (route, method, data, headers = {}) => fetch(base + route, { method, headers: { 'Content-Type': 'application/json', ...headers }, body: JSON.stringify(data) });
  assert.deepEqual(await get('/api/health'), { ok: true });
  const state = await get('/api/state'); state.tasks.push({ id: 'task-1', title: '检查配置', status: 'active' });
  state.settings.apiKey = 'test-secret';
  assert.equal((await send('/api/state', 'PUT', state)).status, 200);
  assert.equal((await get('/api/state')).tasks[0].title, '检查配置');
  const baseline=require('../../frontend/state-merge.js').baseOf(await get('/api/state'));
  const stale=await get('/api/state'),newer=structuredClone(stale);newer.tasks.push({id:'server-created',title:'Agent刚创建的事项',status:'inbox'});core.writeState(newer);
  stale.tasks[0].title='同时手动编辑';stale._clientBase=baseline;
  const merged=await (await send('/api/state','PUT',stale)).json();assert.equal(merged.tasks.find(t=>t.id==='task-1').title,'同时手动编辑');assert.ok(merged.tasks.some(t=>t.id==='server-created'));assert.equal(merged._clientBase,undefined);assert.equal(core.readState()._clientBase,undefined);
  const backup = await get('/api/backup'); assert.equal(backup.settings.apiKey, '');
  backup.tasks[0].title = '导入后的任务';
  const imported = await (await send('/api/backup', 'POST', backup)).json();
  assert.equal(imported.state.settings.apiKey, 'test-secret');
  assert.equal(imported.state.tasks[0].title, '导入后的任务');
  state.settings.apiKey = ''; await send('/api/state', 'PUT', state);
  const result = await (await send('/api/ai/chat', 'POST', { text: '10分钟后提醒我吃饭' })).json();
  assert.equal(result.source, 'local'); assert.equal(result.actions[0].type, 'create_reminder');
  assert.equal((await send('/api/state', 'PUT', {})).status, 400);
  assert.equal((await send('/api/state', 'PUT', state, { Origin: 'https://evil.example' })).status, 403);
  assert.equal((await fetch(base + '/api/state', { method: 'OPTIONS', headers: { Origin: 'http://127.0.0.1:5173' } })).status, 204);
  assert.equal((await fetch(base + '/index.html')).status, 200);
  assert.match(await (await fetch(base + '/api.js')).text(), /fetch\('/);
  assert.equal((await fetch(base + '/package.json')).status, 404);
  assert.equal((await fetch(base + '/api/missing')).status, 404);
  const bytes=Buffer.from([137,80,78,71,13,10,26,10,0,0,0,0]);const hash=require('node:crypto').createHash('sha256').update(bytes).digest('hex');fs.mkdirSync(core.momentMediaDirectory(),{recursive:true});fs.writeFileSync(path.join(core.momentMediaDirectory(),hash+'.png'),bytes);
  const imageResponse=await fetch(base+'/api/moment-media/'+hash+'.png');assert.equal(imageResponse.headers.get('content-type'),'image/png');assert.deepEqual(Buffer.from(await imageResponse.arrayBuffer()),bytes);
  const saved=await get('/api/state');saved.moments=[{id:'photo',content:'咖啡',createdAt:new Date().toISOString(),image:{id:'remote:'+hash+'.png',sourceId:'commons:1',sourceUrl:'https://commons.wikimedia.org/wiki/File:Coffee.jpg',remoteUrl:'https://thumb.wikimedia.org/wikipedia/commons/thumb/a/ab/Coffee.jpg/1280px-Coffee.jpg',label:'Coffee',artist:'Artist',license:'CC BY 4.0'}}];await send('/api/state','PUT',saved);
  const moved = path.join(directory, 'moved');
  assert.equal((await send('/api/storage', 'PUT', { directory: moved })).status, 200);
  assert.equal((await get('/api/storage')).directory, moved);
  assert.equal((await get('/api/state')).tasks[0].id, 'task-1');
  const fallback=await fetch(base+'/api/moment-media/'+hash+'.png',{redirect:'manual'});assert.equal(fallback.status,302);assert.equal(fallback.headers.get('location'),saved.moments[0].image.remoteUrl);
  assert.equal((await send('/api/storage', 'PUT', { directory })).status, 400);
});
